#!/bin/sh
# Install git-graft, the animated git visualizer.
#
#   curl -fsSL https://raw.githubusercontent.com/ashfaqrafin/graft/HEAD/install.sh | sh
#
# Environment:
#   GRAFT_VERSION      release tag to install, e.g. v0.1.0 (default: latest)
#   GRAFT_INSTALL_DIR  where the binary goes (default: ~/.local/bin, or /usr/local/bin as root)
#   GRAFT_SETUP        yes / no: set up `git` integration without asking
#   GRAFT_ARCHIVE      install from a local release archive instead of downloading
set -eu

REPO="ashfaqrafin/graft"
VERSION="${GRAFT_VERSION:-latest}"

say() { printf '\033[1;35m▸\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!\033[0m %s\n' "$*" >&2; }
die() { printf '\033[1;31m✖\033[0m %s\n' "$*" >&2; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }

if [ "$(id -u)" = 0 ]; then
    PREFIX="/usr/local"
    DATA="$PREFIX/share"
else
    PREFIX="$HOME/.local"
    DATA="${XDG_DATA_HOME:-$HOME/.local/share}"
fi
BIN_DIR="${GRAFT_INSTALL_DIR:-$PREFIX/bin}"

have git || warn "git is not installed: git-graft needs it at run time"

case "$(uname -s)" in
    Linux) ;;
    *) die "this installer is for Linux; elsewhere use: cargo install --locked --git https://github.com/$REPO" ;;
esac
case "$(uname -m)" in
    x86_64 | amd64) TARGET="x86_64-unknown-linux-musl" ;;
    aarch64 | arm64) TARGET="aarch64-unknown-linux-musl" ;;
    *) TARGET="" ;;
esac

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT INT TERM

fetch() { # url dest
    if have curl; then
        curl -fsSL --retry 2 -o "$2" "$1"
    elif have wget; then
        wget -q -O "$2" "$1"
    else
        die "need curl or wget to download git-graft"
    fi
}

build_from_source() {
    have cargo || die "no prebuilt binary for $(uname -m), and cargo is not installed (get it from https://rustup.rs)"
    say "building from source with cargo (this takes a minute)"
    cargo install --locked --root "$TMP/cargo" --git "https://github.com/$REPO" git-graft
    mkdir -p "$TMP/pkg"
    cp "$TMP/cargo/bin/git-graft" "$TMP/pkg/git-graft"
}

ARCHIVE="$TMP/graft.tar.gz"
if [ -n "${GRAFT_ARCHIVE:-}" ]; then
    cp "$GRAFT_ARCHIVE" "$ARCHIVE"
elif [ -n "$TARGET" ]; then
    NAME="git-graft-$TARGET.tar.gz"
    if [ "$VERSION" = latest ]; then
        URL="https://github.com/$REPO/releases/latest/download/$NAME"
    else
        URL="https://github.com/$REPO/releases/download/$VERSION/$NAME"
    fi
    say "downloading git-graft ($VERSION, $TARGET)"
    if fetch "$URL" "$ARCHIVE" 2>/dev/null; then
        if fetch "$URL.sha256" "$TMP/sum" 2>/dev/null && have sha256sum; then
            expected="$(cut -d' ' -f1 <"$TMP/sum")"
            actual="$(sha256sum "$ARCHIVE" | cut -d' ' -f1)"
            [ "$expected" = "$actual" ] || die "checksum mismatch for $NAME"
        else
            warn "could not verify the checksum"
        fi
    else
        warn "no release download available"
        rm -f "$ARCHIVE"
    fi
fi

if [ -f "$ARCHIVE" ]; then
    mkdir -p "$TMP/pkg"
    tar -xzf "$ARCHIVE" -C "$TMP/pkg" --strip-components=1
else
    build_from_source
fi
[ -x "$TMP/pkg/git-graft" ] || die "the archive did not contain a git-graft binary"

mkdir -p "$BIN_DIR"
install -m 755 "$TMP/pkg/git-graft" "$BIN_DIR/git-graft"
say "installed $BIN_DIR/git-graft ($("$BIN_DIR/git-graft" --version))"

# Completions and man page, generated by the binary so they always match it.
install_extra() { # dir file generator...
    dir="$1"; file="$2"; shift 2
    mkdir -p "$dir" 2>/dev/null && "$@" >"$dir/$file" 2>/dev/null || true
}
install_extra "$DATA/bash-completion/completions" git-graft "$BIN_DIR/git-graft" completions bash
install_extra "$DATA/zsh/site-functions" _git-graft "$BIN_DIR/git-graft" completions zsh
install_extra "${XDG_CONFIG_HOME:-$HOME/.config}/fish/completions" git-graft.fish "$BIN_DIR/git-graft" completions fish
install_extra "$DATA/man/man1" git-graft.1 "$BIN_DIR/git-graft" man

case ":$PATH:" in
    *":$BIN_DIR:"*) ON_PATH=1 ;;
    *) ON_PATH=0 ;;
esac

# Offer the shell integration that makes plain `git merge` animate.
answer="${GRAFT_SETUP:-}"
if [ -z "$answer" ]; then
    if [ -r /dev/tty ] && [ -w /dev/tty ]; then
        # shellcheck disable=SC2016 # the backticks are literal
        printf 'Make plain `git` commands animate in your shell? [Y/n] ' >/dev/tty
        read -r answer </dev/tty || answer=n
    else
        answer=no
    fi
fi
case "$answer" in
    n | N | no | NO) SETUP=0 ;;
    *) SETUP=1 ;;
esac
if [ "$SETUP" = 1 ]; then
    "$BIN_DIR/git-graft" setup --yes || warn "shell setup failed; run 'git graft setup' later"
fi

echo
if [ "$ON_PATH" = 0 ] && [ "$SETUP" = 0 ]; then
    warn "$BIN_DIR is not on your PATH. Add this to your shell's startup file:"
    echo "    export PATH=\"$BIN_DIR:\$PATH\""
    echo
fi
if [ "$ON_PATH" = 0 ] && [ "$SETUP" = 1 ]; then
    say "done. Open a new terminal, then try:  git graft demo"
else
    say "done. Try:  git graft demo"
fi
[ "$SETUP" = 1 ] || echo "  later:  git graft setup     (makes plain git commands animate)"
